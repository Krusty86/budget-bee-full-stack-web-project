package com.hmi.exp_inc_tracker.controller;

import java.util.Map;

import org.springframework.http.HttpStatus;
import org.springframework.http.ResponseEntity;
import org.springframework.web.bind.annotation.CrossOrigin;
import org.springframework.web.bind.annotation.RequestMapping;
import org.springframework.web.bind.annotation.RequestParam;
import org.springframework.web.bind.annotation.RestController;

import com.hmi.exp_inc_tracker.dto.LoginRequest;
import com.hmi.exp_inc_tracker.dto.PasswordResetRequest;
import com.hmi.exp_inc_tracker.dto.RegisterRequest;
import com.hmi.exp_inc_tracker.entity.PasswordResetToken;
import com.hmi.exp_inc_tracker.entity.User;
import com.hmi.exp_inc_tracker.service.JWTService;
import com.hmi.exp_inc_tracker.service.PasswordResetTokenService;
import com.hmi.exp_inc_tracker.service.UserService;
import lombok.RequiredArgsConstructor;
import org.springframework.web.bind.annotation.PostMapping;
import org.springframework.web.bind.annotation.RequestBody;


@RestController
@CrossOrigin("*")
@RequestMapping("/api/auth")
@RequiredArgsConstructor
public class AuthController {
	private final UserService userService;
	private final JWTService jwtService;
	private final PasswordResetTokenService passwordResetTokenService;
	
	@PostMapping("/login")
	public ResponseEntity<?> login(@RequestBody LoginRequest loginRequest) {
		System.out.println("Email: "+loginRequest.getEmail());
		System.out.println("Password: "+loginRequest.getPassword());
		
		Boolean status = userService.login(loginRequest);
		if(status) {
			System.out.println("Inside Login Status Check");
			// token generated by jwtService (Java Web Token);
			User user = userService.getUserByEmail(loginRequest.getEmail());
			String token = jwtService.generateToken(loginRequest.getEmail());
			return ResponseEntity.ok(Map.of(
					"msg", "Login Success",
					"token",token,
					"userId",user.getId(),
					"user", user
					));
		}
		else {
			System.out.println("Error");
			return ResponseEntity.status(HttpStatus.UNAUTHORIZED)
					.body(Map.of("msg","Invalid email or password"));
		}
				
	}
	
	@PostMapping("/register")
	public ResponseEntity<?> register(@RequestBody RegisterRequest register) {
		User user = userService.register(register);
		if(user!=null)
			return ResponseEntity.status(HttpStatus.OK)
					.body(user);
		else
			return ResponseEntity.status(HttpStatus.EXPECTATION_FAILED)
					.body(Map.of("msg","Failed To Register Your Email"));
	}
	
	@PostMapping("/pwd-reset-request")
	public ResponseEntity<?> passwordResetRequest(@RequestParam String email){
		PasswordResetToken token = passwordResetTokenService.generateOtp(email);
		if(token!=null)
			return ResponseEntity.status(HttpStatus.OK)
					.body(token);
		else
			return ResponseEntity.status(HttpStatus.EXPECTATION_FAILED)
					.body(Map.of("msg","Failed to Request OTP code."));
	}

	
	@PostMapping("/pwd-reset")
	public ResponseEntity<?> passwordReset(@RequestBody PasswordResetRequest pwdReq){
		Boolean status = passwordResetTokenService.verifyOtp(pwdReq.getEmail(), pwdReq.getCode());
		
		if(status) {
			System.out.println("Inside Password Reset");
			User user = userService.getUserByEmail(pwdReq.getEmail());
			
			user = userService.resetPassword(user, pwdReq.getNewPwd());
			if(user!=null)
				return ResponseEntity.status(HttpStatus.OK)
						.body(user);
		}
		return ResponseEntity.status(HttpStatus.EXPECTATION_FAILED)
				.body(Map.of("msg","Invalid OTP or Password"));
	}
	
	
}
